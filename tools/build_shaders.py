#!/usr/bin/env python3
"""Compile Vulkan 1.0 example shaders and embed validated little-endian words."""
import argparse
import pathlib
import struct
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]


def generate():
    lines = ["# Generated by tools/build_shaders.py; edit shaders/indexed.vert or indexed.frag.", "import Base", ""]
    with tempfile.TemporaryDirectory() as temporary:
        for stage, name in (("vert", "vertex_words"), ("frag", "fragment_words")):
            output = pathlib.Path(temporary) / f"indexed.{stage}.spv"
            subprocess.run(["glslc", "--target-env=vulkan1.0", "-O", "-o", str(output),
                            str(ROOT / f"shaders/indexed.{stage}")], check=True)
            subprocess.run(["spirv-val", "--target-env", "vulkan1.0", str(output)], check=True)
            data = output.read_bytes()
            if len(data) % 4 or data[:4] != b"\x03\x02\x23\x07":
                raise ValueError("Expected little-endian SPIR-V")
            words = [str(word) for (word,) in struct.iter_unpack("<I", data)]
            lines.extend([f"def {name}() -> List<U32>:", "  ["])
            lines.extend("    " + ", ".join(words[i:i+8]) + ("," if i+8 < len(words) else "")
                         for i in range(0, len(words), 8))
            lines.extend(["  ]", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "shaders/spirv.bend"
    source = generate()
    if args.check:
        if output.read_text() != source:
            raise SystemExit("shaders/spirv.bend is stale; run tools/build_shaders.py")
    else:
        output.write_text(source)


if __name__ == "__main__":
    main()
