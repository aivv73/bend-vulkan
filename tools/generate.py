#!/usr/bin/env python3
"""Generate the supported Vulkan constants from Khronos vk.xml."""
import argparse
import json
import pathlib
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[1]
GROUPS = (
    "VkResult", "VkPhysicalDeviceType", "VkQueueFlagBits",
    "VkColorSpaceKHR", "VkPresentModeKHR", "VkSurfaceTransformFlagBitsKHR", "VkCompositeAlphaFlagBitsKHR",
    "VkBufferUsageFlagBits", "VkMemoryPropertyFlagBits",
    "VkCommandPoolCreateFlagBits", "VkCommandBufferUsageFlagBits",
    "VkSharingMode", "VkPipelineStageFlagBits", "VkAccessFlagBits",
    "VkFormat", "VkFormatFeatureFlagBits", "VkMemoryHeapFlagBits",
    "VkImageType", "VkImageTiling", "VkImageUsageFlagBits", "VkImageCreateFlagBits",
    "VkImageViewType", "VkImageAspectFlagBits", "VkImageLayout", "VkSampleCountFlagBits",
    "VkAttachmentLoadOp", "VkAttachmentStoreOp",
    "VkShaderStageFlagBits", "VkVertexInputRate", "VkPrimitiveTopology", "VkCullModeFlagBits", "VkFrontFace", "VkCompareOp", "VkColorComponentFlagBits", "VkIndexType",
)


def render(registry):
    root = ET.parse(registry).getroot()
    lines = ["# Generated by tools/generate.py from Khronos vk.xml; do not edit.",
             "import Base", ""]
    for group in GROUPS:
        enums = root.find(f"./enums[@name='{group}']")
        if enums is None:
            raise ValueError(f"missing registry enum group: {group}")
        for enum in enums.findall("enum"):
            if enum.get("api", "vulkan") != "vulkan":
                continue
            if "value" in enum.attrib:
                value = int(enum.attrib["value"], 0) & 0xFFFFFFFF
            elif "bitpos" in enum.attrib:
                value = 1 << int(enum.attrib["bitpos"])
            else:
                continue
            if value > 0xFFFFFFFF:
                raise ValueError(f"{enum.attrib['name']} needs U64")
            lines.extend([f"def {enum.attrib['name']}() -> U32:", f"  {value}", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--registry", default=str(ROOT / "registry/vk.xml"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    bindings = json.loads((ROOT / "tools/bindings.json").read_text())
    effects = []
    registrations = []
    window_registrations = []
    js = ["// Generated native-only backend registrations."]
    for binding in bindings:
        name, arguments, result, native, *policies = binding
        policy = policies[0] if policies else {}
        if len(policies) > 1 or set(policy) - {"return_owner", "native_module"}:
            raise ValueError(f"unsupported binding policy for {name}")
        module = policy.get("native_module", "native")
        if module not in {"native", "window"}:
            raise ValueError(f"unsupported native module for {name}")
        owner = policy.get("return_owner")
        if owner is not None and (type(owner) is not int or not 0 <= owner < len(arguments)
                                  or arguments[owner][1] != "Array<U32>"):
            raise ValueError(f"invalid returned array owner for {name}")
        params = ", ".join(f"{key}: {kind}" for key, kind in arguments)
        output = f"VkResult({result})"
        if owner is not None:
            output = f"{arguments[owner][1]} & {output}"
        effects.extend([f"def {name}({params}) -> IO({output}):", f'  import "./src/{module}.c"',
                        '  import "./src/native.js"', ""])
        target_registrations = window_registrations if module == "window" else registrations
        target_registrations.extend([f"#ifdef CID({name})",
            f"  io_eff(CID({name}), bv_{native});", "#endif"])
        failure = '{ $: CID(Fail), error: io_tup(1610612737, "Vulkan requires a native build: bend example.bend -o build/example") }'
        if owner is not None:
            js.append(f'io_eff(CID({name}), (...args) => io_tup(args[{owner}], {failure}));')
            continue
        js.append(f'io_eff(CID({name}), () => ({{ $: CID(Fail), error: io_tup(1610612737, "Vulkan requires a native build: bend example.bend -o build/example") }}));')
    public = ROOT / "Vulkan.bend"
    before, tail = public.read_text().split("# BEGIN GENERATED EFFECTS\n")
    _, after = tail.split("# END GENERATED EFFECTS")
    api = before + "# BEGIN GENERATED EFFECTS\n" + "\n".join(effects) + "# END GENERATED EFFECTS" + after
    native_file = ROOT / "src/native.c"
    native = native_file.read_text()
    before, tail = native.split("// BEGIN GENERATED REGISTRATIONS\n")
    _, after = tail.split("// END GENERATED REGISTRATIONS")
    native = before + "// BEGIN GENERATED REGISTRATIONS\n" + "\n".join(registrations) + "\n// END GENERATED REGISTRATIONS" + after
    window_file = ROOT / "src/x11.c"
    window = window_file.read_text()
    before, tail = window.split("// BEGIN GENERATED WINDOW REGISTRATIONS\n")
    _, after = tail.split("// END GENERATED WINDOW REGISTRATIONS")
    window = before + "// BEGIN GENERATED WINDOW REGISTRATIONS\n" + "\n".join(window_registrations) + "\n// END GENERATED WINDOW REGISTRATIONS" + after
    bundle = "// Generated by tools/generate.py from native.c and x11.c; do not edit.\n" + native + "\n" + window
    outputs = {window_file: window, ROOT / "src/window.c": bundle,
               ROOT / "src/constants.bend": render(args.registry), public: api,
               native_file: native, ROOT / "src/native.js": "\n".join(js) + "\n"}
    for output, source in outputs.items():
        if args.check:
            if output.read_text() != source:
                raise SystemExit(f"{output.relative_to(ROOT)} is stale; run tools/generate.py")
        else:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(source)


if __name__ == "__main__":
    main()
